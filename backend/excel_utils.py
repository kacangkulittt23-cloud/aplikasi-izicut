"""Excel import parsing and template generation for E-IZICUT.

Supports two workbook formats:
1. LEGACY (the user's existing file): sheets named "TAHUN 2025"/"TAHUN 2026",
   personnel grouped into sections separated by repeated header rows. Satfung is
   derived from the section leader's Jabatan. Columns hold only dates.
2. TEMPLATE (generated by /api/template): flat rows with an explicit SATFUNG
   column and paired "ALASAN ..." reason columns.
"""

